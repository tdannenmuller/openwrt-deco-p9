#!/bin/sh
# Experiment: a "bridge" Wi-Fi link between two Deco P9 running OpenWrt, without relayd:
#   - WDS (4addr): one Deco as access point (wds-ap), the other as client (wds-sta);
#   - 802.11s mesh: both Decos as "mesh point" (mesh), with wpad-mesh.
# Limited to the 2.4 GHz radio by default (radio1, ath9k) and to an isolated test bridge (br-wdstest,
# 10.77.0.x addresses): it is NEVER connected to br-lan, so no loop with the powerline link.
# Says nothing about throughput. See README.md.
#
#   backhaul-test.sh status
#   backhaul-test.sh wds-ap  <ip>      (e.g. 10.77.0.1, on the Deco acting as access point)
#   backhaul-test.sh wds-sta <ip>      (e.g. 10.77.0.2, on the client Deco)
#   backhaul-test.sh mesh    <ip>      (on both Decos, after swap-mesh)
#   backhaul-test.sh probe   <peer_ip>
#   backhaul-test.sh swap-mesh | swap-basic     (switch wpad variant; Wi-Fi down ~30 s)
#   backhaul-test.sh stop                       (remove the whole experiment)
# Variables: AUTOSTOP=<minutes> (default 20, 0 = disabled): automatic "stop" after this delay;
#            RADIO=radio0 CHAN=112 to test 5 GHz (empty CHAN: channel unchanged); repeat for "stop".

# Radio and channel: 2.4 GHz by default (radio1, channel 1). For 5 GHz: RADIO=radio0 CHAN=112 ...
# Empty CHAN = leave the channel alone (use on the Deco whose radio follows the upstream router).
RADIO="${RADIO:-radio1}"
CHAN="${CHAN-1}"
export RADIO CHAN
SSID=WDSTEST
KEY=wdstest-2026
SAVED=/root/backhaul-test.saved
SELF=/root/backhaul-test.sh
PKG=/root/pkg
AUTOSTOP="${AUTOSTOP:-20}"

die() { echo "ERROR: $*" >&2; exit 1; }

net_setup() {
	uci -q delete network.wdstest_dev
	uci -q delete network.wdstest
	uci set network.wdstest_dev=device
	uci set network.wdstest_dev.type=bridge
	uci set network.wdstest_dev.name=br-wdstest
	uci set network.wdstest_dev.bridge_empty=1
	uci set network.wdstest=interface
	uci set network.wdstest.device=br-wdstest
	uci set network.wdstest.proto=static
	uci set network.wdstest.ipaddr="$1"
	uci set network.wdstest.netmask=255.255.255.0
	uci commit network
}

set_channel() {
	[ -n "$CHAN" ] || return 0
	[ -f "$SAVED" ] || uci -q get "wireless.$RADIO.channel" > "$SAVED"
	uci set "wireless.$RADIO.channel=$CHAN"
}

new_iface() {
	uci -q delete wireless.wdstest
	uci set wireless.wdstest=wifi-iface
	uci set wireless.wdstest.device="$RADIO"
	uci set wireless.wdstest.network=wdstest
	uci set wireless.wdstest.key="$KEY"
}

apply() {
	# Two pitfalls met on a Deco used as a relay (relayd + firewall4), temporary (until "stop"):
	# - fw4's input chain has "policy drop" and ignores a bridge outside any zone;
	# - relayd puts an "iif lo lookup 16800" rule before the main table: traffic generated by the Deco
	#   (ping replies) goes to the upstream router instead of the test bridge.
	nft insert rule inet fw4 input iifname "br-wdstest" accept comment "wdstest" 2>/dev/null
	ip rule del to 10.77.0.0/24 lookup main pref 1 2>/dev/null
	ip rule add to 10.77.0.0/24 lookup main pref 1 2>/dev/null
	uci commit wireless
	# Safety net: the test config is written to flash and the "stop" timer does not survive a
	# reboot; if the Deco crashes or is rebooted by hand, the experiment is removed at the next boot.
	if [ -f /etc/rc.local ] && ! grep -q wdstest-cleanup /etc/rc.local; then
		sed -i '/^exit 0/i [ -x /root/backhaul-test.sh ] \&\& /root/backhaul-test.sh stop # wdstest-cleanup' /etc/rc.local
	fi
	/etc/init.d/network reload
	wifi reload "$RADIO"
	if [ "$AUTOSTOP" != 0 ]; then
		setsid sh -c "sleep $((AUTOSTOP * 60)); $SELF stop" </dev/null >/dev/null 2>&1 &
		echo "automatic stop in $AUTOSTOP min ($SELF stop)"
	fi
	echo "applied; wait ~20 s then: $0 status"
}

need_ip() { [ -n "$1" ] || die "IP address expected (e.g. 10.77.0.1)"; }

case "$1" in
status)
	echo "== wpad: $(apk info 2>/dev/null | grep -E '^wpad' | tr '\n' ' ')"
	echo "== radio $RADIO: channel $(uci -q get wireless.$RADIO.channel)"
	echo "== Wi-Fi interfaces"; iw dev | grep -E "Interface|type|ssid|channel"
	echo "== test bridge"; ip addr show br-wdstest 2>&1 | head -4; brctl show br-wdstest 2>&1 | head -5
	echo "== associated stations (2.4 GHz radio)"; iw dev 2>/dev/null | awk '/Interface/{i=$2} /channel .*2[0-9][0-9][0-9] MHz/{print i}' | while read -r i; do iw dev "$i" station dump 2>/dev/null | grep -E "^Station|signal:|tx bitrate"; done
	echo "== mesh"; iw dev 2>/dev/null | awk '/Interface/{i=$2} /type mesh point/{print i}' | while read -r i; do iw dev "$i" mpath dump 2>&1 | head -5; done
	;;
wds-ap)
	need_ip "$2"
	net_setup "$2"; set_channel; new_iface
	uci set wireless.wdstest.mode=ap
	uci set wireless.wdstest.ssid="$SSID"
	uci set wireless.wdstest.hidden=1
	uci set wireless.wdstest.encryption=psk2
	uci set wireless.wdstest.wds=1
	apply
	;;
wds-sta)
	need_ip "$2"
	net_setup "$2"; set_channel; new_iface
	uci set wireless.wdstest.mode=sta
	uci set wireless.wdstest.ssid="$SSID"
	uci set wireless.wdstest.encryption=psk2
	uci set wireless.wdstest.wds=1
	apply
	;;
mesh)
	need_ip "$2"
	apk info -e wpad-mesh-mbedtls >/dev/null 2>&1 || die "wpad-mesh missing: run '$0 swap-mesh' first"
	net_setup "$2"; set_channel; new_iface
	uci set wireless.wdstest.mode=mesh
	uci set wireless.wdstest.mesh_id="$SSID"
	uci set wireless.wdstest.encryption=sae
	apply
	;;
probe)
	need_ip "$2"
	br=br-wdstest
	mine=$(uci -q get network.wdstest.ipaddr); last=${mine##*.}
	mac=02:77:00:00:00:$(printf %02x "$last")
	ip link show "$br" >/dev/null 2>&1 || die "$br missing: run wds-ap / wds-sta / mesh first"
	echo "bridge MAC address forced to $mac (different from the Wi-Fi interface's):"
	echo "frames with this source address only get through if the link is a real bridge (4addr or mesh)."
	ip link set dev "$br" address "$mac" || die "cannot change the bridge address"
	sleep 3
	echo "== ping $2 from $mine"
	ping -c 5 -W 2 "$2"; rc=$?
	echo "== addresses seen by the bridge"; brctl showmacs "$br" 2>&1 | head -8
	[ $rc = 0 ] && echo "RESULT: the link relays a foreign MAC address (real bridge)" || echo "RESULT: NO reply (no real bridge, or link not established: see status)"
	;;
swap-mesh|swap-basic)
	if [ "$1" = swap-mesh ]; then new=wpad-mesh-mbedtls; old=wpad-basic-mbedtls; else new=wpad-basic-mbedtls; old=wpad-mesh-mbedtls; fi
	apk info -e "$new" >/dev/null 2>&1 && die "$new is already installed"
	f=$(ls $PKG/$new-*.apk 2>/dev/null | head -1); [ -n "$f" ] || die "$PKG/$new-*.apk not found"
	echo "replacing $old with $new (Wi-Fi down 30 to 60 s on this Deco, wpad service restart)"
	apk del "$old" && apk add --allow-untrusted --no-network "$f" || { echo "FAILED: reverting to $old"; apk add --allow-untrusted --no-network $PKG/$old-*.apk; die "replacement failed"; }
	# The already-running wpad daemon keeps the old code in memory: without a restart it does not know the
	# "mesh" mode ("too large mode (value=5 max_value=4)") or keeps ignoring the new variant's options.
	/etc/init.d/wpad restart
	sleep 5
	wifi reload
	apk info | grep -E '^wpad'
	;;
stop)
	[ -f /etc/rc.local ] && sed -i '/wdstest-cleanup/d' /etc/rc.local
	ip rule del to 10.77.0.0/24 lookup main pref 1 2>/dev/null
	for h in $(nft -a list chain inet fw4 input 2>/dev/null | sed -n 's/.*comment "wdstest" # handle \([0-9]*\)/\1/p'); do
		nft delete rule inet fw4 input handle "$h"
	done
	uci -q delete wireless.wdstest
	uci -q delete network.wdstest
	uci -q delete network.wdstest_dev
	if [ -f "$SAVED" ]; then
		c=$(cat "$SAVED"); [ -n "$c" ] && uci set "wireless.$RADIO.channel=$c"
		rm -f "$SAVED"
	fi
	uci commit wireless; uci commit network
	/etc/init.d/network reload
	wifi reload "$RADIO"
	echo "experiment removed; channel of $RADIO restored: $(uci -q get wireless.$RADIO.channel)"
	;;
*)
	sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'
	exit 1
	;;
esac
